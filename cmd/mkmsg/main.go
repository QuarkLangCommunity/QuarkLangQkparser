// Command mkmsg packs this package's authored message table (i18n/source/messages.tsv) into
// Go code: one stable ID constant per message, and the canonical text of each message as a
// contiguous blob with an offset table.
//
// It is the syntax layer's half of the message design.  The other half lives in the consumer
// (QuarkLangQkc): its generator reads the same table and checks that every ID this package ships has
// a value in every language that consumer ships.  That is what makes "a new message in this package
// cannot ship untranslated" a build-time fact instead of a runtime hope.
//
// Deterministic by construction: every list is taken in table order, nothing is hashed, and no
// timestamp is written.  Regenerate with `go generate ./...`.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

const (
	sourceDir = "i18n/source"
	outFile   = "messages_gen.go"
	// modulePrefix is stripped from a message id to name its constant: the package already says
	// which module the message belongs to.
	modulePrefix = "parser."
)

// Message is one authored row.
type Message struct {
	ID   string // dotted, stable
	Lang string // the language the text is written in
	Text string // the template, verbs intact
}

// doc is the header of every generated file, so a reader lands on the generator first.
const doc = `// Code generated by cmd/mkmsg from %s. DO NOT EDIT.
//
// The table is the source of truth; this file is its packed form.  A message's identity is its ID
// constant, never its text, so rephrasing a message does not change which message it is.
`

// parseTable reads the tab-separated message table. Each data line has exactly three columns — id,
// lang, text — and the text is strconv.Quote'd so that tabs, newlines and quotes round-trip exactly
// and a template may contain anything. Lines whose text begins with '#' are comments.
func parseTable(name string) ([]Message, error) {
	raw, err := os.ReadFile(name)
	if err != nil {
		return nil, err
	}
	var out []Message
	seen := map[string]bool{}
	for i, line := range strings.Split(string(raw), "\n") {
		if strings.TrimSpace(line) == "" || strings.HasPrefix(strings.TrimSpace(line), "#") {
			continue
		}
		parts := strings.SplitN(line, "\t", 3)
		if len(parts) != 3 {
			return nil, fmt.Errorf("%s:%d: want 3 tab-separated columns (id, lang, text), got %d", name, i+1, len(parts))
		}
		id, lang := parts[0], parts[1]
		text, uerr := strconv.Unquote(strings.TrimSpace(parts[2]))
		if uerr != nil {
			return nil, fmt.Errorf("%s:%d: text is not a quoted Go string: %v", name, i+1, uerr)
		}
		if strings.ContainsAny(id, " \t") || id == "" {
			return nil, fmt.Errorf("%s:%d: id %q is empty or contains whitespace", name, i+1, id)
		}
		if key := id + "\x00" + lang; seen[key] {
			return nil, fmt.Errorf("%s:%d: duplicate row for %s/%s", name, i+1, id, lang)
		} else {
			seen[key] = true
		}
		out = append(out, Message{ID: id, Lang: lang, Text: text})
	}
	return out, nil
}

// messagesInOrder returns the authored messages of one language, in table order, with the first
// appearance of each id deciding its position. The order is the blob's order, so it is the authored
// order and never a map's.
func messagesInOrder(all []Message, lang string) []Message {
	var out []Message
	seen := map[string]bool{}
	for _, m := range all {
		if m.Lang != lang || seen[m.ID] {
			continue
		}
		seen[m.ID] = true
		out = append(out, m)
	}
	return out
}

// constName turns a dotted message id into its Go constant: "parser.nesting_too_deep" becomes
// "IDNestingTooDeep" in this package.
func constName(id string) string {
	if !strings.HasPrefix(id, modulePrefix) {
		// A foreign domain (the consumer's) is not this package's constant to name.
		return ""
	}
	return "ID" + camel(strings.TrimPrefix(id, modulePrefix))
}

// camel turns "nesting_too_deep" into "NestingTooDeep".
func camel(s string) string {
	var b strings.Builder
	for _, part := range strings.Split(s, "_") {
		if part == "" {
			continue
		}
		b.WriteString(strings.ToUpper(part[:1]))
		b.WriteString(part[1:])
	}
	return b.String()
}

// quote renders a Go string literal, preferring a raw literal when the text has no backquote and no
// carriage return, so a template stays readable in the generated file.
func quote(s string) string {
	if !strings.ContainsAny(s, "`\r") {
		return "`" + s + "`"
	}
	return strconv.Quote(s)
}

// generate renders the generated file: the ID block, the offset table and the texts.
func generate(all []Message) ([]byte, error) {
	msgs := messagesInOrder(all, "en")
	if len(msgs) == 0 {
		return nil, fmt.Errorf("no messages")
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, doc, sourceDir+"/messages.tsv")
	fmt.Fprintf(&b, "\npackage qkparser\n\n")
	fmt.Fprintf(&b, "// ID identifies one message of this package. It is stable: never renumber, never recycle.\n")
	fmt.Fprintf(&b, "type ID uint16\n\n")
	fmt.Fprintf(&b, "// Message IDs. The text of an ID is the English source; it is not the ID.\nconst (\n")
	for i, m := range msgs {
		name := constName(m.ID)
		if name == "" {
			return nil, fmt.Errorf("id %q does not belong to this module (%q prefix)", m.ID, modulePrefix)
		}
		fmt.Fprintf(&b, "\t%s ID = %d\n", name, i)
	}
	fmt.Fprintf(&b, ")\n\n")

	// The offset table and the blob: message k occupies blob[offsets[k-1]:offsets[k]].
	fmt.Fprintf(&b, "// msgOffsets[k] is the end offset of message k in msgBlob (start is the previous entry, 0 for the first).\n")
	fmt.Fprintf(&b, "var msgOffsets = [...]uint32{\n")
	total := 0
	for _, m := range msgs {
		total += len(m.Text)
		fmt.Fprintf(&b, "\t%d,\n", total)
	}
	fmt.Fprintf(&b, "}\n\n")
	fmt.Fprintf(&b, "// msgBlob is every message's English text, back to back, in ID order.\n")
	fmt.Fprintf(&b, "const msgBlob = %s\n\n", quote(concat(msgs)))

	fmt.Fprintf(&b, "// Messages returns every message this package ships, in ID order, as the (ID, text) pairs the\n")
	fmt.Fprintf(&b, "// consumer's catalog generator validates its own table against.\n")
	fmt.Fprintf(&b, "func Messages() []Message {\n")
	fmt.Fprintf(&b, "\tout := make([]Message, 0, len(msgOffsets))\n")
	fmt.Fprintf(&b, "\tfor i := range msgOffsets {\n")
	fmt.Fprintf(&b, "\t\tout = append(out, Message{ID: ID(i), Text: msgText(ID(i))})\n")
	fmt.Fprintf(&b, "\t}\n\treturn out\n}\n\n")
	fmt.Fprintf(&b, "// Message is one message of this package: its stable ID and its canonical English text.\n")
	fmt.Fprintf(&b, "type Message struct {\n\tID   ID\n\tText string\n}\n\n")
	fmt.Fprintf(&b, "// msgText returns the canonical English text of an ID, read out of the blob.\n")
	fmt.Fprintf(&b, "func msgText(id ID) string {\n")
	fmt.Fprintf(&b, "\ti := int(id)\n\tif i < 0 || i >= len(msgOffsets) {\n\t\treturn \"\"\n\t}\n")
	fmt.Fprintf(&b, "\tstart := uint32(0)\n\tif i > 0 {\n\t\tstart = msgOffsets[i-1]\n\t}\n")
	fmt.Fprintf(&b, "\treturn msgBlob[start:msgOffsets[i]]\n}\n")

	return format.Source(b.Bytes())
}

// concat joins the texts back to back; the offset table carries the boundaries, so no separator is
// needed and a message may contain any byte.
func concat(msgs []Message) string {
	var b strings.Builder
	for _, m := range msgs {
		b.WriteString(m.Text)
	}
	return b.String()
}

// check reports whether the file on disk is exactly what generate would write.
func check(path string, want []byte) error {
	got, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	if !bytes.Equal(got, want) {
		return fmt.Errorf("%s is out of date: regenerate it with `go generate ./...`", path)
	}
	return nil
}

func main() {
	table := flag.String("table", filepath.Join(sourceDir, "messages.tsv"), "authored message table")
	out := flag.String("out", outFile, "generated file to write")
	doCheck := flag.Bool("check", false, "fail when the generated file is out of date instead of writing it")
	flag.Parse()

	all, err := parseTable(*table)
	if err != nil {
		fmt.Fprintln(os.Stderr, "mkmsg:", err)
		os.Exit(1)
	}
	// Every id must carry exactly the languages the table declares; a row set that lost a language
	// is the failure this generator exists to make impossible.
	langs := map[string][]string{}
	for _, m := range all {
		langs[m.ID] = append(langs[m.ID], m.Lang)
	}
	ids := make([]string, 0, len(langs))
	for id := range langs {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	for _, id := range ids {
		if len(langs[id]) != 1 || langs[id][0] != "en" {
			fmt.Fprintf(os.Stderr, "mkmsg: %s: this package authors the English source only, got languages %v\n", id, langs[id])
			os.Exit(1)
		}
	}

	src, err := generate(all)
	if err != nil {
		fmt.Fprintln(os.Stderr, "mkmsg:", err)
		os.Exit(1)
	}
	if *doCheck {
		if err := check(*out, src); err != nil {
			fmt.Fprintln(os.Stderr, "mkmsg:", err)
			os.Exit(1)
		}
		fmt.Printf("mkmsg: %s is up to date (%d messages)\n", *out, len(messagesInOrder(all, "en")))
		return
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "mkmsg:", err)
		os.Exit(1)
	}
	fmt.Printf("mkmsg: wrote %s (%d messages)\n", *out, len(messagesInOrder(all, "en")))
}
